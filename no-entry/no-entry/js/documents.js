function openDoc(id) {
  const doc = DOCS[id];
  if (!doc) return;
  ESC.collectDoc(id);
  if (id === 'accident_summary') ESC.setFlag('found_accident');
  if (id === 'saeki_letter') ESC.setFlag('found_saeki_letter');
  if (id === 'fragment_note' || id === 'quiet_observation') ESC.setFlag('deeper_layer');
  ESC.openModal(doc.html);
}
